#!/bin/sh
# Builds snmptrapd.conf from the snmp_trap secret and starts snmptrapd in the foreground.
# Secret file format (shell KEY=value, see secrets/snmp_trap.env.example).
set -eu

SECRET_FILE=/run/secrets/snmp_trap
CONF=/tmp/snmptrapd.conf

if [ ! -r "$SECRET_FILE" ]; then
  echo "trapd: missing secret $SECRET_FILE" >&2
  exit 1
fi
set -a
# shellcheck disable=SC1090
. "$SECRET_FILE"
set +a

: "${TRAPD_ENGINE_ID:?set TRAPD_ENGINE_ID in the snmp_trap secret}"
: "${TRAP_USER:?set TRAP_USER in the snmp_trap secret}"
: "${TRAP_AUTH_PASS:?set TRAP_AUTH_PASS in the snmp_trap secret}"
: "${TRAP_PRIV_PASS:?set TRAP_PRIV_PASS in the snmp_trap secret}"
TRAP_AUTH_PROTOCOL="${TRAP_AUTH_PROTOCOL:-SHA}"
TRAP_PRIV_PROTOCOL="${TRAP_PRIV_PROTOCOL:-AES}"

umask 077
{
  echo "# generated by entrypoint.sh, do not edit"
  # Fixed engine ID: devices sending informs are configured with this value.
  echo "exactEngineID $TRAPD_ENGINE_ID"
  echo "disableAuthorization no"
  # Informs: trapd is the authoritative engine, one user works for every device.
  echo "createUser $TRAP_USER $TRAP_AUTH_PROTOCOL \"$TRAP_AUTH_PASS\" $TRAP_PRIV_PROTOCOL \"$TRAP_PRIV_PASS\""
  # Plain v3 traps: the sender is authoritative, so each device's engine ID needs its own user entry.
  for engine_id in ${TRAP_DEVICE_ENGINE_IDS:-}; do
    echo "createUser -e $engine_id $TRAP_USER $TRAP_AUTH_PROTOCOL \"$TRAP_AUTH_PASS\" $TRAP_PRIV_PROTOCOL \"$TRAP_PRIV_PASS\""
  done
  echo "authUser log,execute $TRAP_USER priv"
  # Optional v2c for legacy devices only (listed exceptions).
  if [ -n "${TRAP_V2C_COMMUNITY:-}" ]; then
    echo "authCommunity log,execute $TRAP_V2C_COMMUNITY"
  fi
  echo "traphandle default /usr/local/bin/trap2json"
} > "$CONF"

echo "trapd: engine ID $TRAPD_ENGINE_ID, user $TRAP_USER ($TRAP_AUTH_PROTOCOL/$TRAP_PRIV_PROTOCOL), listening on udp/162"

# -f foreground, -Lo log to stdout, -On numeric OIDs, -n no DNS lookups, -C ignore default config files.
exec snmptrapd -f -Lo -On -n -C -c "$CONF" udp:162
